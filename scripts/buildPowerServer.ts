/**
 * Builds the HexCard power's MCP server (spec 07 design §Build script, D1, D10):
 *
 *   npm run build:power               # write powers/hexcard/server/hexcard-mcp.mjs and the licence files
 *   npm run build:power -- --check    # exit 1 if any of them differs from a fresh build
 *
 * Vite's build() bundles src/power/main.ts for Node into one unminified ES module with Zod
 * inlined; only `node:` built-ins stay as imports. The script also copies the licence texts the
 * power redistributes (Requirement 1.7) and fails when the bundle holds code of a package under
 * node_modules that has no licence entry, or when the output has a second chunk, the repository's
 * absolute path or a `file://` URL (Requirement 3.4).
 *
 * src/power/__tests__/serverFile.test.ts calls buildPowerServer() and fails when the committed
 * server file is stale; it never writes the file.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build, type Rolldown } from "vite";

/** `${PLUGIN_ROOT}/server/hexcard-mcp.mjs`, the server file text of mcp.json (Requirement 2.2). */
export const SERVER_FILE_ARG = "${PLUGIN_ROOT}/server/hexcard-mcp.mjs";
/** The server file's path relative to the power folder, with `/` separators. */
const SERVER_FILE_RELATIVE = SERVER_FILE_ARG.slice("${PLUGIN_ROOT}/".length);

/** Absolute paths, from this script's import.meta.url. Never written into the output. */
const REPO_ROOT = fileURLToPath(new URL("..", import.meta.url)).replace(/\/$/, "");
export const POWER_DIR: string = join(REPO_ROOT, "powers", "hexcard");
export const SERVER_FILE_PATH: string = join(POWER_DIR, ...SERVER_FILE_RELATIVE.split("/"));

/** Build command named in the staleness failure message (Requirement 3.5). */
export const BUILD_POWER_COMMAND = "npm run build:power";

const ENTRY = "src/power/main.ts";
const BANNER = `// GENERATED by scripts/buildPowerServer.ts from the HexCard sources. Do not edit; run ${BUILD_POWER_COMMAND}.`;

/**
 * Third-party packages that may be bundled, with the licence file each one ships and the file of
 * the power folder its text is copied to (Requirement 1.7, design D10).
 */
const PACKAGE_LICENCES: Readonly<Record<string, { source: string; target: string }>> = {
  zod: { source: "node_modules/zod/LICENSE", target: "licenses/zod-LICENSE.txt" },
};

/** Font licences: the fenced block under each heading of public/fonts/LICENSES.md. */
const FONT_LICENCES: readonly { heading: string; target: string }[] = [
  { heading: "## Pixel Operator: Creative Commons Zero 1.0 Universal", target: "licenses/PixelOperator-CC0-1.0.txt" },
  { heading: "## Fairfax Serif: SIL Open Font License 1.1", target: "licenses/FairfaxSerif-OFL-1.1.txt" },
];

export interface PowerBuild {
  /** The server file text. */
  serverFile: string;
  /** Packages under node_modules whose code is in the bundle, sorted (today ["zod"]). */
  bundledPackages: string[];
  /** Licence file path relative to POWER_DIR -> text (Requirement 1.7). */
  licenceFiles: Record<string, string>;
}

const readRepoFile = (relative: string): string => readFileSync(join(REPO_ROOT, relative), "utf8");

/**
 * The lines inside the first fenced block after the line `heading` of `markdown`, joined with LF
 * and ended with one LF. Throws when the heading or a closed block is missing.
 */
export function fencedBlockAfter(markdown: string, heading: string): string {
  const lines = markdown.split(/\r?\n/);
  const at = lines.indexOf(heading);
  if (at < 0) throw new Error(`buildPowerServer: heading "${heading}" not found in public/fonts/LICENSES.md`);
  const open = lines.findIndex((line, index) => index > at && line.startsWith("```"));
  const close = open < 0 ? -1 : lines.findIndex((line, index) => index > open && line.startsWith("```"));
  if (open < 0 || close < 0) throw new Error(`buildPowerServer: no fenced block under "${heading}"`);
  return `${lines.slice(open + 1, close).join("\n")}\n`;
}

/** The package name of every /node_modules/<package>/ module id, sorted and without repeats. */
export function packagesOf(moduleIds: readonly string[]): string[] {
  const names = new Set<string>();
  for (const id of moduleIds) {
    const pieces = id.replace(/\\/g, "/").split("/node_modules/");
    if (pieces.length < 2) continue;
    // The innermost node_modules folder names the package (nested installs included).
    const name = /^((?:@[^/]+\/)?[^/]+)\//.exec(pieces.at(-1)!)?.[1];
    if (name !== undefined) names.add(name);
  }
  return [...names].sort();
}

/** Builds in memory. Writes nothing. */
export async function buildPowerServer(): Promise<PowerBuild> {
  const result = await build({
    configFile: false,
    envFile: false,
    root: REPO_ROOT,
    mode: "production",
    base: "/",
    logLevel: "silent",
    publicDir: false,
    build: {
      write: false,
      ssr: ENTRY,
      target: "node22",
      minify: false,
      sourcemap: false,
      rolldownOptions: {
        output: { format: "es", entryFileNames: "hexcard-mcp.mjs", codeSplitting: false, banner: BANNER },
      },
    },
    ssr: { noExternal: true, target: "node" },
  });
  if (Array.isArray(result) || !("output" in result)) throw new Error("buildPowerServer: expected one build output");
  const outputs = (result as Rolldown.RolldownOutput).output;
  if (outputs.length !== 1 || outputs[0].type !== "chunk") {
    throw new Error(`buildPowerServer: expected exactly one chunk, got ${outputs.map((item) => item.fileName).join(", ")}`);
  }
  const chunk = outputs[0];
  const serverFile = chunk.code;
  if (!serverFile.startsWith(BANNER)) throw new Error("buildPowerServer: the server file does not start with the banner");
  if (serverFile.includes(REPO_ROOT)) throw new Error("buildPowerServer: the server file contains the repository's absolute path");
  if (serverFile.includes("file://")) throw new Error("buildPowerServer: the server file contains a file:// URL");

  const bundledPackages = packagesOf(chunk.moduleIds);
  const missing = bundledPackages.filter((name) => !Object.prototype.hasOwnProperty.call(PACKAGE_LICENCES, name));
  if (missing.length > 0) {
    throw new Error(`buildPowerServer: bundled packages without a licence entry: ${missing.join(", ")}; add them to PACKAGE_LICENCES`);
  }

  const licenceFiles: Record<string, string> = { LICENSE: readRepoFile("LICENSE") };
  for (const name of bundledPackages) licenceFiles[PACKAGE_LICENCES[name].target] = readRepoFile(PACKAGE_LICENCES[name].source);
  const fontLicences = readRepoFile("public/fonts/LICENSES.md");
  for (const { heading, target } of FONT_LICENCES) licenceFiles[target] = fencedBlockAfter(fontLicences, heading);

  return { serverFile, bundledPackages, licenceFiles };
}

/** Every file the build writes: path relative to POWER_DIR -> text. */
function outputFiles(power: PowerBuild): Record<string, string> {
  return { [SERVER_FILE_RELATIVE]: power.serverFile, ...power.licenceFiles };
}

function readOrNull(path: string): string | null {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}

/** `npm run build:power`: writes the server file and the licence files. `--check`: exits 1 if any differs. */
export async function main(argv: readonly string[]): Promise<void> {
  const files = outputFiles(await buildPowerServer());
  if (argv.includes("--check")) {
    const stale = Object.entries(files)
      .filter(([relative, text]) => readOrNull(join(POWER_DIR, ...relative.split("/"))) !== text)
      .map(([relative]) => relative);
    if (stale.length > 0) {
      process.stderr.write(`powers/hexcard is out of date (${stale.join(", ")}); run ${BUILD_POWER_COMMAND}.\n`);
      process.exitCode = 1;
    } else {
      process.stdout.write("powers/hexcard is up to date.\n");
    }
    return;
  }
  for (const [relative, text] of Object.entries(files)) {
    const path = join(POWER_DIR, ...relative.split("/"));
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
    process.stdout.write(`wrote powers/hexcard/${relative} (${Buffer.byteLength(text)} bytes)\n`);
  }
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) await main(process.argv.slice(2));
